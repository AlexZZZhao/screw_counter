import cv2,numpy as np,time
for n in ['gt27_0','frame_focused','white']:
    f=cv2.imread(n+'.png'); g=cv2.cvtColor(f,cv2.COLOR_BGR2GRAY)
    H,W=g.shape; s=4; sm=cv2.resize(g,(W//s,H//s),interpolation=cv2.INTER_AREA)
    _,b=cv2.threshold(cv2.GaussianBlur(sm,(0,0),2),0,255,cv2.THRESH_BINARY+cv2.THRESH_OTSU)
    nl,lab,st,cen=cv2.connectedComponentsWithStats(b); i=1+np.argmax(st[1:,4])
    cs,_=cv2.findContours((lab==i).astype(np.uint8),0,2); hull=cv2.convexHull(max(cs,key=cv2.contourArea))
    bm=np.zeros_like(sm); cv2.drawContours(bm,[hull],-1,255,-1)
    M=cv2.moments(hull); cx,cy=int(M['m10']/M['m00']),int(M['m01']/M['m00'])
    bg=cv2.medianBlur(sm,15)
    t,_=cv2.threshold(bg[bm>0].reshape(-1,1),0,255,cv2.THRESH_BINARY+cv2.THRESH_OTSU)
    side=(bg>t) if bg[cy,cx]>t else (bg<=t)
    side=(side&(bm>0)).astype(np.uint8)
    nl,lab,st,_=cv2.connectedComponentsWithStats(side,connectivity=4)
    fl=(lab==lab[cy,cx]).astype(np.uint8)
    cs,_=cv2.findContours(fl,0,2); h2=cv2.convexHull(max(cs,key=cv2.contourArea))
    v=cv2.cvtColor(sm,cv2.COLOR_GRAY2BGR); cv2.drawContours(v,[h2],-1,(0,0,255),1); cv2.drawContours(v,[hull],-1,(0,255,0),1)
    print(n,t,bg[cy,cx],cv2.contourArea(h2)/cv2.contourArea(hull))
    cv2.imwrite('approaches/tmp/fl13_%s.png'%n,cv2.resize(v,None,fx=2,fy=2)[50:520,320:660])
